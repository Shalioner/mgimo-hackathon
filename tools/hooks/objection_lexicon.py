def _fix_token(tok: str) -> str:
    """Смешанные токены приводим к алфавиту большинства: «xyйня» → «хуйня», «fuсk» (кириллическая с) → «fuck»,
    «пи3дец» → «пиздец», «sh1t» → «shit». Чисто цифровые токены сюда не попадают (вырезаны раньше)."""
    n_cyr, n_lat = len(CYR.findall(tok)), len(LAT.findall(tok))
    has_digit = any(ch.isdigit() or ch in "@$" for ch in tok)
    if not (n_cyr and n_lat) and not has_digit:
        return tok
    return tok.translate(LAT_TO_CYR) if n_cyr >= n_lat and n_cyr else tok.translate(CYR_TO_LAT)


NAMES = re.compile(r"\bz[. ]?a[. ]?e[. ]?b[. ]?a[. ]?l\b\.?", re.IGNORECASE)  # название чужого навыка — не ругань


def normalize(text: str) -> str:
    t = NAMES.sub(" ", unicodedata.normalize("NFKC", text)).lower().replace("ё", "е")
    t = MARKDOWN.sub(lambda m: m.group(1) or m.group(2), t)
    t = NUMBERS.sub(" ", t)  # «45s», «360x640», «31%» не должны стать буквами через 3→з, 0→о
    t = SPACED.sub(lambda m: re.sub(r"[.\-_ ]", "", m.group(0)), t)
    t = TOKEN.sub(lambda m: _fix_token(m.group(0)), t)
    return REPEATS.sub(r"\1", t)


